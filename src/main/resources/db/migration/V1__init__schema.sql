
CREATE TABLE billing_document_type
(
    code        VARCHAR(2)   NOT NULL,
    description VARCHAR(255) NOT NULL,
    PRIMARY KEY (code)
);

CREATE TABLE clients
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    document_type   VARCHAR(10)  NOT NULL CHECK (document_type IN ('DNI', 'CUIT', 'PASSPORT')),
    number          VARCHAR(10)  NOT NULL,
    postal_code     VARCHAR(10),
    document_number VARCHAR(15)  NOT NULL,
    phone_number    VARCHAR(20)  NOT NULL,
    city            VARCHAR(50)  NOT NULL,
    country         VARCHAR(50)  NOT NULL,
    first_name      VARCHAR(50)  NOT NULL,
    last_name       VARCHAR(50)  NOT NULL,
    province        VARCHAR(50)  NOT NULL,
    email           VARCHAR(100),
    street          VARCHAR(100) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_client_document UNIQUE (document_type, document_number)
);

CREATE TABLE units
(
    id          VARCHAR(3)  NOT NULL,
    description VARCHAR(50) NOT NULL UNIQUE,
    PRIMARY KEY (id)
);

CREATE TABLE products
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code       VARCHAR(50)  NOT NULL UNIQUE,
    name       VARCHAR(70)  NOT NULL UNIQUE,
    unit_price NUMERIC(8, 2) NOT NULL,
    unit_id    VARCHAR(3)   NOT NULL, -- Foreign key placeholder pointing to the unit.
    PRIMARY KEY (id)
);

CREATE TABLE orders
(
    id                         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    correlative                INTEGER,
    date                       DATE,
    serie                      VARCHAR(4),
    total                      NUMERIC(8, 2),
    client_id                  BIGINT     NOT NULL, -- Foreign key placeholder pointing to the client.
    code_billing_document_type VARCHAR(2) NOT NULL, -- Foreign key placeholder pointing to the billing document type.
    PRIMARY KEY (id)
);

CREATE TABLE order_details
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    quantity   INTEGER,
    subtotal   NUMERIC(8, 2) NOT NULL,
    unit_price NUMERIC(8, 2) NOT NULL,
    order_id   BIGINT       NOT NULL, -- Foreign key placeholder pointing to the order.
    product_id BIGINT       NOT NULL, -- Foreign key placeholder pointing to the product.
    PRIMARY KEY (id)
);

CREATE TABLE roles
(
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(20) NOT NULL UNIQUE,
    PRIMARY KEY (id)
);

CREATE TABLE users
(
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY,
    email    VARCHAR(100) NOT NULL UNIQUE,
    password VARCHAR(200) NOT NULL,
    active   BOOLEAN      NOT NULL,
    PRIMARY KEY (id)
);

-- USERS_ROLES JUNCTION TABLE (Many-to-Many Relationship)
CREATE TABLE users_roles
(
    user_id BIGINT NOT NULL,      -- References the specific user.
    role_id BIGINT NOT NULL,      -- References the specific role.
    PRIMARY KEY (user_id, role_id) -- Composite primary key. Prevents assigning duplicate roles to the same user.
);


-- CONSTRAINTS & RELATIONSHIPS (Foreign Keys)

-- Connects the products table to the units table.
ALTER TABLE IF EXISTS products
    ADD CONSTRAINT fk_products_unit
    FOREIGN KEY (unit_id) REFERENCES units (id);

-- Connects the orders table to the clients table.
ALTER TABLE IF EXISTS orders
    ADD CONSTRAINT fk_orders_client
    FOREIGN KEY (client_id) REFERENCES clients (id);

-- Connects the orders table to the billing document types table.
ALTER TABLE IF EXISTS orders
    ADD CONSTRAINT fk_orders_billing_document_type
    FOREIGN KEY (code_billing_document_type) REFERENCES billing_document_type (code);

-- Connects the order details table to the orders table.
ALTER TABLE IF EXISTS order_details
    ADD CONSTRAINT fk_order_details_order
    FOREIGN KEY (order_id) REFERENCES orders (id);

-- Connects the order details table to the products table.
ALTER TABLE IF EXISTS order_details
    ADD CONSTRAINT fk_order_details_product
    FOREIGN KEY (product_id) REFERENCES products (id);

-- Connects the junction table to the users table.
ALTER TABLE IF EXISTS users_roles
    ADD CONSTRAINT fk_users_roles_user
    FOREIGN KEY (user_id) REFERENCES users (id);

-- Connects the junction table to the roles table.
ALTER TABLE IF EXISTS users_roles
    ADD CONSTRAINT fk_users_roles_role
    FOREIGN KEY (role_id) REFERENCES roles (id);
